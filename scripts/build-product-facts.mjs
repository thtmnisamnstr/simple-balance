/**
 * Write `docs/product/facts.json`, the machine-readable description of what
 * this product offers a person.
 *
 * **Why this file exists.** The marketing site at smpl.money is a separate
 * repository that makes claims about this one — a free plan keeping three
 * accounts, a paid plan that removes the ads, what each is called. Nothing
 * over there can read TypeScript, and nothing over here knows that site
 * exists. Before this file the only mechanism was somebody remembering, and
 * it had already failed once: this application displayed "Plus" while the
 * site said "Premium".
 *
 * So the contract is published rather than remembered, and the site records
 * which version of it it last agreed with.
 *
 * **Two halves, and the file says which is which.** `derived` is read out of
 * the source at build time and `tests/product-facts.test.ts` fails if the
 * committed file disagrees with the constants. `declared` is everything the
 * source cannot know — the prices live at Stripe, and the capability list is
 * a description of the product rather than a property of a module. A reader
 * can tell at a glance which fields are guaranteed and which are somebody's
 * sentence.
 *
 *   npx tsx scripts/build-product-facts.mjs
 *
 * `npm run verify` does not run it. The test compares instead, so a stale
 * file fails rather than being silently rewritten by the thing checking it.
 */
import { writeFileSync } from "node:fs";
import { MAX_FREE_ACCOUNTS, PLAN_LABELS, plans } from "../src/shared/domain.js";
import { APP_NAME, APP_VERSION } from "../src/shared/version.js";

/**
 * What the source cannot tell us.
 *
 * Prices are at Stripe; this application holds only the price *ids*, and an
 * id is not a number a marketing page can print. The capabilities are the
 * product's own description of itself, maintained here because this is the
 * repository that would know when one stopped being true.
 */
const declared = {
  prices: {
    currency: "USD",
    monthly: "3.00",
    yearly: "30.00",
    note: "The annual plan is two months cheaper than paying monthly.",
  },
  /**
   * Everything a person gets, on every plan. The paid plan adds no
   * capability — it raises the account limit and removes the advertising —
   * so this is deliberately one list rather than two.
   */
  capabilities: [
    "Double-entry ledger, where every transaction settles to zero",
    "Unlimited transactions and unlimited currencies",
    "Net worth, income and expenses, spending by category, cash flow, balance sheet and trial balance",
    "Budgets per category or group, with carry-over",
    "CSV import with format detection and duplicate review",
    "CSV export, including multi-currency round trips",
    "Recurring transactions that propose themselves",
    "Transaction templates",
    "Bulk edit and delete, up to ten thousand rows",
    "Split transactions across several categories",
    "An account register with the balance before and after every posting",
    "Append-only audit history",
    "An MCP server with the same capabilities as the web app",
    "Email reminders, where a mail server is configured",
  ],
  /** What the paid plan changes, and nothing else does. */
  /*
   * "No account limit" stopped being true when freezing arrived: a free plan
   * keeps every account somebody has, and limits how many are usable at once.
   * What the paid plan adds is the use of all of them.
   */
  paidPlanAdds: ["Every account stays usable", "No advertising"],
};

const facts = {
  $schema: "https://smpl.money/schemas/product-facts.json",
  $comment:
    "Generated by scripts/build-product-facts.mjs. Do not edit by hand — " +
    "tests/product-facts.test.ts fails when this disagrees with the source.",
  derived: {
    appName: APP_NAME,
    appVersion: APP_VERSION,
    /** The wire values, in the order the enum declares them. */
    planKeys: [...plans],
    plans: {
      free: {
        label: PLAN_LABELS.free,
        accountLimit: MAX_FREE_ACCOUNTS,
        advertising: true,
      },
      plus: {
        label: PLAN_LABELS.plus,
        // Null rather than a large number: the paid plan has no limit, and a
        // number would be a limit somebody would eventually print.
        accountLimit: null,
        advertising: false,
      },
    },
  },
  declared,
};

export function buildProductFacts() {
  return facts;
}

// Running this file writes; importing it does not.
if (process.argv[1]?.endsWith("build-product-facts.mjs")) {
  const path = "docs/product/facts.json";
  writeFileSync(path, `${JSON.stringify(facts, null, 2)}\n`);
  console.log(`wrote ${path}`);
}
